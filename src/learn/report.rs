//! Formats and persists correction suggestions for the user.

use crate::core::utils::ensure_project_path_safe;
use crate::learn::detector::CorrectionRule;
use anyhow::{Context, Result};
use std::collections::HashMap;
use std::fs;
use std::io::Write;
use std::path::Path;

pub const RULES_PATH: &str = ".claude/rules/cli-corrections.md";

pub fn format_console_report(
    rules: &[CorrectionRule],
    total_corrections: usize,
    sessions: usize,
    days: u64,
) -> String {
    let mut output = String::new();

    output.push_str(&format!(
        "Bushido Learn -- {} rules from {} corrections ({} sessions, {} days)\n",
        rules.len(),
        total_corrections,
        sessions,
        days
    ));

    if rules.is_empty() {
        output.push_str("\nNo CLI corrections detected.\n");
        return output;
    }

    output.push('\n');

    for rule in rules {
        let count_marker = if rule.occurrences > 1 {
            format!("[{}x] ", rule.occurrences)
        } else {
            "     ".to_string()
        };

        output.push_str(&format!(
            "{}{}  →  {}\n",
            count_marker, rule.wrong_pattern, rule.right_pattern
        ));

        // Show error snippet (first line only)
        let error_line = rule.example_error.lines().next().unwrap_or("").trim();
        if !error_line.is_empty() {
            output.push_str(&format!("     Error: {}\n", error_line));
        }
    }

    output
}

pub fn write_rules_file(rules: &[CorrectionRule], project_root: &Path) -> Result<()> {
    let root = project_root
        .canonicalize()
        .context("Failed to resolve project root")?;
    let path = root.join(RULES_PATH);
    ensure_project_path_safe(&root, &path)?;

    // Create parent directory if it doesn't exist
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }

    let mut content = String::new();
    content.push_str("# CLI Corrections (auto-generated by bdo learn)\n");
    content.push_str("# Run `bdo learn --write-rules` to update\n\n");

    if rules.is_empty() {
        content.push_str("No CLI corrections detected yet.\n");
        return persist_rules_file(&root, &path, &content);
    }

    // Group by base command
    let mut grouped: HashMap<String, Vec<&CorrectionRule>> = HashMap::new();
    for rule in rules {
        grouped
            .entry(rule.base_command.clone())
            .or_default()
            .push(rule);
    }

    // Sort base commands alphabetically
    let mut base_commands: Vec<String> = grouped.keys().cloned().collect();
    base_commands.sort();

    for base_cmd in base_commands {
        let rules_for_cmd = grouped.get(&base_cmd).unwrap();

        // Capitalize first letter for section header
        let section_header = capitalize_first(&base_cmd);
        content.push_str(&format!("## {}\n", section_header));

        for rule in rules_for_cmd {
            let occurrence_note = if rule.occurrences > 1 {
                format!(" (seen {}x)", rule.occurrences)
            } else {
                String::new()
            };

            content.push_str(&format!(
                "- Use `{}` not `{}`{}\n",
                rule.right_pattern, rule.wrong_pattern, occurrence_note
            ));
        }

        content.push('\n');
    }

    persist_rules_file(&root, &path, &content)
}

fn persist_rules_file(root: &Path, path: &Path, content: &str) -> Result<()> {
    ensure_project_path_safe(root, path)?;
    let parent = path.parent().context("Missing rules directory")?;
    let mut file = tempfile::NamedTempFile::new_in(parent)?;
    file.write_all(content.as_bytes())?;
    // Never canonicalize the destination or truncate its existing inode:
    // replacement leaves hardlink referents unchanged too.
    ensure_project_path_safe(root, path)?;
    file.persist(path)
        .with_context(|| format!("Failed to replace {}", path.display()))?;
    Ok(())
}

fn capitalize_first(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::learn::detector::ErrorType;

    #[test]
    fn test_format_console_report_empty() {
        let report = format_console_report(&[], 0, 0, 30);
        assert!(report.contains("0 rules"));
        assert!(report.contains("0 corrections"));
        assert!(report.contains("No CLI corrections detected"));
    }

    #[test]
    fn test_format_console_report_with_rules() {
        let rules = vec![
            CorrectionRule {
                wrong_pattern: "git commit --ammend".to_string(),
                right_pattern: "git commit --amend".to_string(),
                error_type: ErrorType::UnknownFlag,
                occurrences: 3,
                base_command: "git commit".to_string(),
                example_error: "error: unexpected argument '--ammend'".to_string(),
            },
            CorrectionRule {
                wrong_pattern: "gh pr edit -t".to_string(),
                right_pattern: "gh pr edit --title".to_string(),
                error_type: ErrorType::UnknownFlag,
                occurrences: 1,
                base_command: "gh pr".to_string(),
                example_error: "unknown flag: -t".to_string(),
            },
        ];

        let report = format_console_report(&rules, 4, 10, 30);
        assert!(report.contains("2 rules"));
        assert!(report.contains("4 corrections"));
        assert!(report.contains("[3x]"));
        assert!(report.contains("--ammend"));
        assert!(report.contains("--amend"));
        assert!(report.contains("Error: error: unexpected argument"));
    }

    #[test]
    fn test_write_rules_file_markdown() {
        let rules = vec![CorrectionRule {
            wrong_pattern: "git commit --ammend".to_string(),
            right_pattern: "git commit --amend".to_string(),
            error_type: ErrorType::UnknownFlag,
            occurrences: 3,
            base_command: "git commit".to_string(),
            example_error: "error: unexpected argument '--ammend'".to_string(),
        }];

        let temp_dir = tempfile::tempdir().unwrap();
        let path = temp_dir.path().join(RULES_PATH);

        write_rules_file(&rules, temp_dir.path()).unwrap();

        let content = fs::read_to_string(&path).unwrap();
        assert!(content.contains("# CLI Corrections"));
        assert!(content.contains("## Git commit"));
        assert!(content.contains("Use `git commit --amend` not `git commit --ammend`"));
        assert!(content.contains("(seen 3x)"));
    }

    #[cfg(unix)]
    #[test]
    fn test_write_rules_file_rejects_external_file_symlink() {
        use std::os::unix::fs::symlink;

        let project = tempfile::tempdir().unwrap();
        let outside = tempfile::tempdir().unwrap();
        let victim = outside.path().join("victim.md");
        fs::write(&victim, "outside sentinel").unwrap();
        let target = project.path().join(RULES_PATH);
        fs::create_dir_all(target.parent().unwrap()).unwrap();
        symlink(&victim, &target).unwrap();

        let result = write_rules_file(&[], project.path());
        assert_eq!(fs::read_to_string(&victim).unwrap(), "outside sentinel");
        assert!(result.is_err(), "a repository symlink must be rejected");
        assert!(fs::symlink_metadata(&target)
            .unwrap()
            .file_type()
            .is_symlink());
    }

    #[cfg(unix)]
    #[test]
    fn test_write_rules_file_rejects_dangling_and_relative_file_links() {
        use std::os::unix::fs::symlink;

        for exists in [false, true] {
            let project = tempfile::tempdir().unwrap();
            let victim = project.path().join("victim.md");
            if exists {
                fs::write(&victim, "sentinel").unwrap();
            }
            let target = project.path().join(RULES_PATH);
            fs::create_dir_all(target.parent().unwrap()).unwrap();
            symlink("../../victim.md", &target).unwrap();

            assert!(write_rules_file(&[], project.path()).is_err());
            if exists {
                assert_eq!(fs::read_to_string(&victim).unwrap(), "sentinel");
            } else {
                assert!(!victim.exists());
            }
            assert_eq!(
                fs::read_link(&target).unwrap(),
                Path::new("../../victim.md")
            );
        }
    }

    #[cfg(unix)]
    #[test]
    fn test_write_rules_file_rejects_parent_links_before_creating_directories() {
        use std::os::unix::fs::symlink;

        for linked_component in [".claude", ".claude/rules"] {
            let project = tempfile::tempdir().unwrap();
            let outside = tempfile::tempdir().unwrap();
            let link = project.path().join(linked_component);
            fs::create_dir_all(link.parent().unwrap()).unwrap();
            symlink(outside.path(), &link).unwrap();

            assert!(write_rules_file(&[], project.path()).is_err());
            assert_eq!(fs::read_dir(outside.path()).unwrap().count(), 0);
            assert!(fs::symlink_metadata(&link)
                .unwrap()
                .file_type()
                .is_symlink());
        }
    }

    #[test]
    fn test_write_rules_file_updates_normal_file_and_empty_rules() {
        let project = tempfile::tempdir().unwrap();
        let target = project.path().join(RULES_PATH);
        write_rules_file(&[], project.path()).unwrap();
        let expected = "# CLI Corrections (auto-generated by bdo learn)\n\
                        # Run `bdo learn --write-rules` to update\n\n\
                        No CLI corrections detected yet.\n";
        assert_eq!(fs::read_to_string(&target).unwrap(), expected);
        fs::write(&target, "old rules".repeat(100)).unwrap();
        write_rules_file(&[], project.path()).unwrap();
        assert_eq!(fs::read_to_string(&target).unwrap(), expected);
        assert_eq!(fs::read_dir(target.parent().unwrap()).unwrap().count(), 1);
    }

    #[test]
    fn test_write_rules_file_replaces_hardlink_without_modifying_other_name() {
        let project = tempfile::tempdir().unwrap();
        let victim = project.path().join("outside-name.md");
        fs::write(&victim, "sentinel").unwrap();
        let target = project.path().join(RULES_PATH);
        fs::create_dir_all(target.parent().unwrap()).unwrap();
        fs::hard_link(&victim, &target).unwrap();

        write_rules_file(&[], project.path()).unwrap();
        assert_eq!(fs::read_to_string(&victim).unwrap(), "sentinel");
        assert!(fs::read_to_string(&target)
            .unwrap()
            .contains("# CLI Corrections"));
    }

    #[cfg(unix)]
    #[test]
    fn test_write_rules_file_accepts_an_aliased_project_root() {
        use std::os::unix::fs::symlink;
        let temp = tempfile::tempdir().unwrap();
        let project = temp.path().join("project");
        fs::create_dir(&project).unwrap();
        let alias = temp.path().join("alias");
        symlink(&project, &alias).unwrap();
        write_rules_file(&[], &alias).unwrap();
        assert!(project.join(RULES_PATH).is_file());
    }
}
